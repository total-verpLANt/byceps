def _hex_hits(path):
    text = strip_comments(path.read_text(encoding='utf-8'))
    return [
        (match.start(), match.group()) for match in HEX_COLOUR.finditer(text)
    ]


def _line_of(path, offset):
    text = path.read_text(encoding='utf-8')
    return text.count('\n', 0, offset) + 1


def _hex_outside_era_palettes(path):
    """Return hex values in `path` that are not era 2/3 custom properties."""
    css = strip_comments(path.read_text(encoding='utf-8'))
    offending = []
    for selector, declarations, offset in parse_blocks(css):
        for name, value in declarations.items():
            if not HEX_COLOUR.search(value):
                continue
            if selector in HEX_ERA_BLOCK_SELECTORS and name.startswith('--'):
                continue
            line = _line_of(path, offset + css[offset:].find(name))
            offending.append(
                f'{_rel(path)}:{line}: {name}: {value} in {selector}'
            )
    return offending


def test_hex_literals_only_in_allowed_files():
    offending = []
    for path in _css_files():
        if path.name in HEX_ALLOWED_FILE_WIDE:
            continue
        if path.name in HEX_ALLOWED_IN_ERA_BLOCKS:
            offending.extend(_hex_outside_era_palettes(path))
            continue
        offending.extend(
            f'{_rel(path)}:{_line_of(path, offset)}: {value}'
            for offset, value in _hex_hits(path)
        )

    assert not offending, '\n'.join(offending)


def test_hygiene_scans_cover_the_shipped_files():
    css_names = {path.name for path in _css_files()}
    js_names = {path.name for path in _js_files()}

    assert HEX_ALLOWED_FILE_WIDE | HEX_ALLOWED_IN_ERA_BLOCKS <= css_names
    assert {'gv-look.js', 'gv-home.js', 'gv-topic.js'} <= js_names
    assert HEX_COLOUR.search('color: #FFF;')
    assert HEX_COLOUR.search('color: #f39200;')
    assert not HEX_COLOUR.search('#top, #con-log')
    assert _hex_hits(STATIC_DIR / 'style' / 'gv-home.css')


