def _brace_problem(css):
    """Return a description of the first brace imbalance, if any."""
    depth = 0
    quote = None
    index = 0
    while index < len(css):
        char = css[index]
        if quote:
            if char == '\\':
                index += 1
            elif char == quote:
                quote = None
        elif css.startswith('/*', index):
            end = css.find('*/', index + 2)
            if end == -1:
                return 'unterminated comment'
            index = end + 1
        elif char in '"\'':
            quote = char
        elif char == '{':
            depth += 1
        elif char == '}':
            depth -= 1
            if depth < 0:
                line = css.count('\n', 0, index) + 1
                return f'unmatched closing brace at line {line}'
        index += 1
    if quote:
        return 'unterminated string'
    if depth:
        return f'{depth} unclosed brace(s)'
    return None


@pytest.mark.parametrize('path', _css_files(), ids=_rel)
def test_css_braces_balanced(path):
    assert _brace_problem(path.read_text(encoding='utf-8')) is None


def test_brace_check_detects_imbalance():
    assert _brace_problem('a { b: c; } /* { */ d { e: "}"; }') is None
    assert _brace_problem('a { b: c;') == '1 unclosed brace(s)'
    assert _brace_problem('a { b: c; } }').startswith('unmatched closing')
    assert _brace_problem('a { b: "c; }') == 'unterminated string'


