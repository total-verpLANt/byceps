# Case-sensitive on purpose: `ico--glass` and `ico--hourglass-half` are
# mandatory icon names.
GLAS_SIM_ERA_ZERO = re.compile(
    r'Glas|glas-|data-era="0"|\bsim-|\.sim\b|tv-picker|tv-trigger'
)
INTERNAL_PATH_OR_ATTRIBUTION = re.compile(
    r'/workspace|\.kevins_workflow|claude|anthropic|artifact|prototyp'
    r'|webfonts-helper|fonts\.googleapis|fonts\.gstatic|generated by',
    re.IGNORECASE,
)
EXTERNAL_URL = re.compile(r'https?://')
SITE_FILE_TARGET = re.compile(r"url_for_site_file\('([^']+)'\)")
HEX_COLOUR = re.compile(
    r'#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})\b'
)
FONT_URL = re.compile(r'url\(\s*[\'"]?([^\'")]+?)[\'"]?\s*\)')

HEX_ALLOWED_FILE_WIDE = {
    'gv-tokens.css',
    'gv-chrome.css',
    'gv-lan-tournament.css',
    'gv-topic.css',
}
HEX_ALLOWED_IN_ERA_BLOCKS = {'gv-home.css'}
HEX_ERA_BLOCK_SELECTORS = {':root[data-era="2"]', ':root[data-era="3"]'}


def _text_files(*roots, include_binary=False):
    """Yield `(path, text)` for every file below `roots`.

    Binary files are skipped unless `include_binary` is set, in which case
    they are decoded as Latin-1 so that ASCII patterns still match.
    """
    for root in roots:
        for path in sorted(root.rglob('*')):
            if not path.is_file():
                continue
            data = path.read_bytes()
            if b'\0' not in data:
                yield path, data.decode('utf-8', errors='replace')
            elif include_binary:
                yield path, data.decode('latin-1')


def _rel(path):
    return path.relative_to(SITE_DIR).as_posix()


def _matches(pattern, files):
    """Return `path:line: text` for every match of `pattern`."""
    hits = []
    for path, text in files:
        for match in pattern.finditer(text):
            line = text.count('\n', 0, match.start()) + 1
            hits.append(f'{_rel(path)}:{line}: {match.group()!r}')
    return hits


def _css_files():
    return sorted(STATIC_DIR.rglob('*.css'))


def _js_files():
    return sorted((STATIC_DIR / 'behavior').glob('*.js'))


def _site_file_targets():
    targets = set()
    for _, text in _text_files(OVERRIDES_DIR):
        targets.update(SITE_FILE_TARGET.findall(text))
    return sorted(targets)


def _font_urls():
    css = strip_comments(FONTS_CSS.read_text(encoding='utf-8'))
    return sorted(set(FONT_URL.findall(css)))


def test_no_glas_sim_or_era_zero_in_site():
    hits = _matches(GLAS_SIM_ERA_ZERO, _text_files(STATIC_DIR, OVERRIDES_DIR))

    assert not hits, '\n'.join(hits)


def test_no_internal_paths_or_attribution_in_shipped_assets():
    hits = _matches(
        INTERNAL_PATH_OR_ATTRIBUTION,
        _text_files(STATIC_DIR, OVERRIDES_DIR, include_binary=True),
    )

    assert not hits, '\n'.join(hits)


def test_no_external_urls_in_static():
    files = [
        (path, text)
        for path, text in _text_files(STATIC_DIR)
        if path.suffix in {'.css', '.js'}
    ]
    assert files

    hits = _matches(EXTERNAL_URL, files)

    assert not hits, '\n'.join(hits)


